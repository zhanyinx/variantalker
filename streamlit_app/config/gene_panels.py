"""The predefined gene panels, and the option list that names them.

Nothing but data. It is 3,600 lines because each panel is one gene per line, and it is
its own module for exactly that reason: it used to sit in the middle of
``config/constants.py``, where it was 90% of the file and every other constant in the app
was on the far side of it.

Read through one door: :data:`PREDEFINED_GENE_SETS`, which
``filters.gene_lists.panel_symbols`` resolves a panel name against. The six panel constants
have no consumer of their own — they exist to be named in that mapping.
``page_modules/data_loading.py`` did import :data:`ONCOKB_GENES` directly, but never used
it; that import is gone.

Deliberately still Python rather than a JSON or newline-delimited asset beside it. A data
file would have to be bundled into the ``.dmg`` and ``.exe`` builds, which means editing
``build/`` — and packaging is out of scope for the cleanup this module came out of, so the
panels stay importable and the build spec stays untouched.
"""

